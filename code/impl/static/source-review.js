/* Replace only read-only source content; preserve all drafts and floating windows. */
(function () {
  'use strict';
  const box = document.getElementById('cmd-source-review');
  if (!box) return;
  const content = box.querySelector('[data-source-review-content]');
  const notice = box.querySelector('[data-source-review-notice]');
  const context = document.getElementById('sop-source-context');
  const contextContent = context && context.querySelector('[data-context-content]');
  const contextNotice = context && context.querySelector('[data-context-notice]');
  let busy = false;
  async function refresh() {
    if (busy || document.hidden) return;
    busy = true;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 8000);
    try {
      const response = await fetch('/sand/source-review?event_id=' + encodeURIComponent(box.dataset.event),
        {cache:'no-store', signal:controller.signal});
      const data = await response.json();
      if (!response.ok || data.event_id !== box.dataset.event) {
        content.replaceChildren();
        box.dataset.revision = '-1';
        if (context) {contextContent.replaceChildren(); context.dataset.revision = '-1';}
        throw new Error(data.error || '当前事件资料不可用。');
      }
      if (Number(data.revision) !== Number(box.dataset.revision)) {
        const opened = new Set([...content.querySelectorAll('article details[open]')]
          .map(node => node.closest('article').dataset.sourceRecord));
        // HTML is generated by the same server renderer as initial paint;
        // every source value is escaped there. No business forms live here.
        content.innerHTML = data.content_html;
        for (const row of content.querySelectorAll('article')) {
          if (opened.has(row.dataset.sourceRecord)) row.querySelector('details').open = true;
        }
        box.dataset.revision = data.revision;
      }
      if (context && Number(data.revision) !== Number(context.dataset.revision)) {
        if (typeof data.context_html !== 'string') throw new Error('共同依据内容缺失。');
        const opened = new Set([...contextContent.querySelectorAll('details[open]')]
          .map(node => node.dataset.contextSubject));
        contextContent.innerHTML = data.context_html;
        for (const row of contextContent.querySelectorAll('details')) row.open = opened.has(row.dataset.contextSubject);
        context.dataset.revision = data.revision;
        context.dataset.fingerprint = data.context_fingerprint;
      }
      notice.textContent = '';
      if (contextNotice) contextNotice.textContent = '';
    } catch (error) {
      notice.textContent = '资料更新失败：' + (error.name === 'AbortError' ? '读取超过 8 秒' : error.message)
        + '；当前显示可能已过时。';
      if (contextNotice) contextNotice.textContent = notice.textContent;
    }
    finally { clearTimeout(timeout); busy = false; }
  }
  /* 3 分钟一轮，与数据更新周期一致；提交动作后由调用方立即刷新。 */
  setInterval(refresh, 180000);
  document.addEventListener('visibilitychange', refresh);
}());
